def execute(args):
    encoder = run_dir = manifest = None
    try:
        data = read_dataset(args.dataset)
        validation = inspect_dataset(data)
        if args.command == 'validate':
            return {'status': validation['status'], 'validation': validation}, 0 if not validation['errors'] else 1
        require(re.fullmatch('[0-9a-fA-F]{40}', args.model_revision) is not None, 'invalid_model_revision')
        require(args.batch_size > 0, 'invalid_batch_size')
        model_path = Path(args.model_path)
        reject_links(model_path)
        model_path = model_path.resolve()
        if args.command == 'train':
            root = private_path(args.output_root)
            dataset_path = private_path(args.dataset)
            require(not root.is_relative_to(model_path) and not dataset_path.is_relative_to(model_path),
                    'output_or_dataset_inside_model')
            require(not model_path.is_relative_to(root), 'model_inside_output')
            root.mkdir(parents=True, exist_ok=True)
            run_dir = root / (datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + uuid.uuid4().hex)
            run_dir.mkdir(exist_ok=False)
            manifest = {'schema_version': 1, 'tool_version': TOOL_VERSION, 'complete': False,
                        'status': 'running', 'started_at': timestamp(), 'outputs': {},
                        'dataset_sha256': dataset_hash(data), 'contract_snapshot': CONTRACT_SNAPSHOT,
                        'contract_snapshot_algorithm': CONTRACT_SNAPSHOT_ALGORITHM,
                        'script_sha256': file_hash(Path(__file__)),
                        'python': platform.python_version(), 'platform': platform.platform(),
                        'device': args.device, 'batch_size': args.batch_size,
                        'preprocessing': 'rerank_original'}
            atomic_json(run_dir / 'manifest.json', manifest)
            atomic_json(run_dir / 'validation.json', validation)
        if validation['errors']:
            result, code = {'status': 'validation_failed', 'validation': validation}, 1
        elif args.command == 'train' and not validation['training_allowed']:
            result, code = {'status': 'review_required', 'error_code': 'human_review_required'}, 2
        else:
            progress('model_preflight')
            # Silence dependency output that may include submitted inputs or local paths.
            with open(os.devnull, 'w') as sink, redirect_stdout(sink), redirect_stderr(sink):
                versions = load_training_dependencies()
                encoder = Encoder(model_path, args.model_revision, args.device, args.batch_size)
                encoder.load()
                preflight = encoder.preflight(data['cases'])
                preflight['numerical_comparison'] = (encoder.numerical_comparison()
                    if preflight['status'] == 'passed' else {'status': 'not_run', 'reason': 'token_failure'})
                encoder.verify()
            require(dataset_hash(read_dataset(args.dataset)) == dataset_hash(data), 'training_inputs_changed')
            preflight.update(dependencies=versions, review_required=validation['review_required'],
                             training_allowed=validation['training_allowed'] and preflight['status'] == 'passed')
            if run_dir:
                manifest.update(dependencies=versions, model_identity=encoder.model_identity)
                atomic_json(run_dir / 'preflight.json', preflight)
            if preflight['status'] != 'passed':
                result, code = {'status': 'preflight_failed', 'preflight': preflight}, 1
            elif args.command == 'preflight':
                result, code = {'status': 'preflight_passed', 'preflight': preflight}, 0
            else:
                progress('embedding_training_evaluation')
                with open(os.devnull, 'w') as sink, redirect_stdout(sink), redirect_stderr(sink):
                    artifact, report = train_loaded(encoder, data)
                    encoder.verify()
                require(dataset_hash(read_dataset(args.dataset)) == dataset_hash(data), 'training_inputs_changed')
                encoder.close()
                encoder = None
                atomic_json(run_dir / 'training-report.json', report)
                atomic_json(run_dir / 'candidate.json', artifact)
                manifest['outputs'] = {name: digest(value) for name, value in
                                       [('training-report.json', report), ('candidate.json', artifact)]}
                passed = all(v for k, v in report['gates'].items() if k != 'latency')
                result, code = {'status': 'candidate_ready_for_benchmark' if passed else 'quality_failed',
                                'gates': report['gates']}, 0 if passed else 1
        if encoder is not None:
            encoder.close()
            encoder = None
        if manifest:
            manifest.update(result, complete=result['status'] in ('candidate_ready_for_benchmark', 'quality_failed'),
                            finished_at=timestamp(), exit_code=code)
            atomic_json(run_dir / 'manifest.json', manifest)
            result['run_directory'] = str(run_dir)
        return result, code
    except (Exception, KeyboardInterrupt) as exc:
        interrupted = isinstance(exc, KeyboardInterrupt)
        safe_errors = {'training_fold_missing_class', 'human_review_required'}
        error_code = ('interrupted' if interrupted else str(exc) if isinstance(exc, Failure)
                      or (isinstance(exc, ValueError) and str(exc) in safe_errors) else 'intent_training_failed')
        if isinstance(exc, ImportError):
            error_code = 'dependency_unavailable'
        if 'torch' in sys.modules and isinstance(exc, sys.modules['torch'].OutOfMemoryError):
            error_code = 'out_of_memory_reduce_batch_size'
        result = {'status': 'interrupted' if interrupted else 'failed', 'error_code': error_code}
        code = 130 if interrupted else 2
        if manifest:
            result['run_directory'] = str(run_dir)
            manifest.update(result, complete=False, finished_at=timestamp(), exit_code=code)
            try:
                atomic_json(run_dir / 'manifest.json', manifest)
            except OSError:
                result['manifest_update_failed'] = True
        return result, code
    finally:
        if encoder is not None:
            try:
                encoder.close()
            except Exception:
                pass


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    for name in ('validate', 'preflight', 'train'):
        command = commands.add_parser(name)
        command.add_argument('--dataset', required=True)
        if name != 'validate':
            command.add_argument('--model-path', required=True)
            command.add_argument('--model-revision', required=True)
            command.add_argument('--device', choices=('cuda', 'cpu'), default='cuda')
            command.add_argument('--batch-size', type=int, default=16)
        if name == 'train':
            command.add_argument('--output-root', required=True)
    args = parser.parse_args(argv)
    result, code = execute(args)
    print(json.dumps(result, ensure_ascii=True, allow_nan=False))
    return code


if __name__ == '__main__':
    raise SystemExit(main())
