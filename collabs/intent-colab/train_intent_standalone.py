class Encoder:
    def __init__(self, model_path, revision, device, batch_size):
        reject_links(model_path)
        self.path = Path(model_path).resolve()
        self.revision, self.device, self.batch_size = revision.lower(), device, batch_size
        self.model = None

    def load(self):
        import torch
        require(self.device != 'cuda' or torch.cuda.is_available(), 'cuda_unavailable')
        if self.device == 'cuda':
            torch.backends.cuda.matmul.allow_tf32 = False
            torch.backends.cudnn.allow_tf32 = False
        from sentence_transformers import SentenceTransformer
        self.fingerprint = model_fingerprint(self.path)
        self.model = SentenceTransformer(str(self.path), device=self.device,
                                        local_files_only=True, trust_remote_code=False)
        self.model.float().eval()
        require(self.model.get_sentence_embedding_dimension() == 384, 'model_dimensions')
        self.verify()

    @property
    def model_identity(self):
        return identity(self.revision, self.fingerprint, True)

    def verify(self):
        require(model_fingerprint(self.path) == self.fingerprint, 'model_changed')

    def preflight(self, cases):
        limit = min(self.model.max_seq_length, self.model.tokenizer.model_max_length)
        require(type(limit) is int and limit > 0, 'invalid_model_token_limit')
        checks = []
        for index, case in enumerate(cases):
            content = 'query: ' + normalize_question(case['question'])
            count = len(self.model.tokenizer(content, add_special_tokens=True,
                                             truncation=False)['input_ids'])
            checks.append({'case_index': index, 'token_count': count, 'limit': limit,
                           'status': 'passed' if count <= limit else 'exceeded'})
        return {'status': 'passed' if all(c['status'] == 'passed' for c in checks) else 'failed',
                'identity': self.model_identity, 'checks': checks}

    def _encode_texts(self, questions):
        inputs = ['query: ' + normalize_question(q) for q in questions]
        vectors = self.model.encode(inputs, batch_size=self.batch_size, precision='float32',
                                    normalize_embeddings=True, convert_to_numpy=True,
                                    show_progress_bar=False, device=self.device)
        require(vectors.shape == (len(inputs), 384) and np.isfinite(vectors).all(),
                'invalid_query_vector')
        # Match retrieval's post-encode Python float normalization exactly.
        result = []
        for vector in vectors:
            values = vector.tolist()
            norm = math.hypot(*values)
            require(math.isfinite(norm) and norm > 0, 'invalid_query_vector')
            result.append([v / norm for v in values])
        return np.asarray(result)

    def encode(self, cases):
        return self._encode_texts([c['question'] for c in cases])

    def numerical_comparison(self):
        if self.device != 'cuda':
            return {'status': 'not_run', 'reason': 'cpu_selected'}
        questions = ['Điều kiện nghỉ phép là gì?', 'Tôi đang thuộc phòng ban nào?', 'Xin chào!']
        gpu = self._encode_texts(questions)
        try:
            self.model.to('cpu')
            self.device = 'cpu'
            cpu = self._encode_texts(questions)
        finally:
            self.model.to('cuda')
            self.device = 'cuda'
        return {'status': 'measured', 'synthetic_cases': len(questions),
                'max_abs_difference': float(np.max(np.abs(gpu - cpu))),
                'minimum_cosine': float(np.min(np.sum(gpu * cpu, axis=1))),
                'bit_identical_required': False,
                'limitation': 'diagnostic_only_not_quality_or_runtime_acceptance'}

    def close(self):
        self.model = None
        if 'torch' in sys.modules and sys.modules['torch'].cuda.is_available():
            sys.modules['torch'].cuda.empty_cache()


def train_loaded(encoder, data):
    """Shared by batch CLI and legacy trainer; returns the existing artifact schema."""
    artifact, report = train(encoder.encode(data['cases']), data['cases'], encoder.model_identity)
    report['dataset_sha256'] = dataset_hash(data)
    report['candidate_payload_sha256'] = digest(artifact)
    artifact['acceptance'] = {'reviewed': True, 'dataset_sha256': dataset_hash(data),
                              'report_sha256': digest(report), 'gates': report['gates']}
    validate_artifact(artifact, artifact['identity'], require_accepted=False)
    return artifact, report


