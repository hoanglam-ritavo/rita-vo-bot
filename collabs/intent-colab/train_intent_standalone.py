def atomic_json(path, data):
    temporary = path.with_name('.' + path.name + '.' + uuid.uuid4().hex + '.tmp')
    try:
        with temporary.open('x', encoding='utf-8') as stream:
            json.dump(data, stream, ensure_ascii=False, indent=2, allow_nan=False)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def file_hash(path):
    reject_links(path)
    with path.open('rb') as stream:
        before = os.fstat(stream.fileno())
        result = hashlib.file_digest(stream, 'sha256').hexdigest()
        after = os.fstat(stream.fileno())
    require((before.st_size, before.st_mtime_ns) == (after.st_size, after.st_mtime_ns),
            'input_changed_during_read')
    return result


def model_fingerprint(path):
    reject_links(path)
    require(path.is_dir(), 'local_model_missing')
    files, queue = {}, [path]
    while queue:
        for item in sorted(queue.pop().iterdir()):
            reject_links(item)
            if item.is_dir():
                queue.append(item)
            elif item.is_file():
                files[item.relative_to(path).as_posix()] = file_hash(item)
            else:
                raise Failure('nonregular_model_file')
    require(bool(files), 'local_model_empty')
    return digest(files)


def normalize_question(question):
    require(isinstance(question, str) and bool(question.strip()), 'invalid_question')
    question = question.strip()
    require(len(question) <= 8000, 'question_too_long')
    # Original rerank variant only: no typo-corrected variant is used for intent.
    return ' '.join(unicodedata.normalize('NFC', question).split())


