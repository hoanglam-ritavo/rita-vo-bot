CONTRACT_FILES = (
    'src/intent/runtime.py', 'src/intent/dataset.py', 'src/intent/training.py',
    'src/intent/preparation.py', 'src/retrieval/reranking.py', 'src/ingestion/embeddings.py')


def select(relative, names):
    source = (ROOT / relative).read_text(encoding='utf-8')
    selected = []
    for node in ast.parse(source).body:
        name = getattr(node, 'name', None)
        if isinstance(node, ast.Assign):
            name = node.targets[0].id if isinstance(node.targets[0], ast.Name) else None
        if name in names:
            selected.append(ast.get_source_segment(source, node))
    if len(selected) != len(names):
        raise ValueError('incomplete_contract_extraction')
    return '\n\n'.join(selected)


