def render():
    snapshot = {name: text_hash(ROOT / name) for name in CONTRACT_FILES}
    parts = [HEADER, 'CONTRACT_SNAPSHOT_ALGORITHM = ' + repr(SNAPSHOT_ALGORITHM),
             'CONTRACT_SNAPSHOT = ' + repr(snapshot),
             select('src/intent/runtime.py', {'SOURCES', 'STYLES', 'GATES', 'digest', 'identity',
                                             'scores', 'classify', 'validate_artifact'}),
             select('src/intent/dataset.py', {'inspect_dataset', 'validate_dataset', 'dataset_hash'}),
             select('src/intent/training.py', {'fit_head', 'accepted_mask', 'source_metrics',
                                              'calibrate', 'evaluate', 'train'}),
             (HERE / 'standalone_runtime.part').read_text(encoding='utf-8')]
    return '\n\n'.join(parts).rstrip() + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args(argv)
    result, code = check_or_write({HERE / 'train_intent_standalone.py': render()}, args.write)
    print(json.dumps(result))
    return code


if __name__ == '__main__':
    raise SystemExit(main())
